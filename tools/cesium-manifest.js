#!/usr/bin/env node
'use strict';
/**
 * Record Cesium's public API surface, so globe.js can be checked against it.
 *
 * globe.js was written against CesiumJS from memory and is loaded from a CDN
 * at runtime, so nothing in this repository could tell whether the symbols it
 * calls exist. A misremembered class or option name would fail only in a
 * reader's browser, and the stubbed tests would stay green - which is exactly
 * how the pane regression shipped.
 *
 * The full package is twenty megabytes and has no business in CI, so this
 * extracts the names alone from the real published type definitions and writes
 * a manifest small enough to commit. Regenerate it when the pinned version
 * moves:
 *
 *   npm pack cesium@<version>
 *   tar -xzf cesium-<version>.tgz package/Source/Cesium.d.ts
 *   node tools/cesium-manifest.js package/Source/Cesium.d.ts test/cesium-api.json <version>
 */
const fs = require('fs');

const [, , dts, out, version] = process.argv;
if (!dts || !out || !version) {
  console.error('usage: cesium-manifest.js <Cesium.d.ts> <manifest.json> <version>');
  process.exit(2);
}
const lines = fs.readFileSync(dts, 'utf8').split('\n');

/** Every top-level exported name: what `Cesium.X` may legally be. */
const exported = new Set();
for (const l of lines) {
  const m = l.match(/^export (?:declare )?(?:abstract )?(class|namespace|enum|function|const|type|interface) ([A-Za-z_$][\w$]*)/);
  if (m) exported.add(m[2]);
}

/** The members of one block, so `Cesium.X.y` can be checked too. */
function membersOf(name) {
  const start = lines.findIndex(l =>
    new RegExp('^export (?:declare )?(?:abstract )?(?:class|namespace|enum) ' + name + '\\b').test(l));
  if (start < 0) return [];
  let depth = 0, end = lines.length;
  for (let i = start; i < lines.length; i++) {
    depth += (lines[i].match(/\{/g) || []).length - (lines[i].match(/\}/g) || []).length;
    if (depth === 0 && i > start) { end = i; break; }
  }
  const body = lines.slice(start, end + 1);
  const found = new Set();
  for (const l of body) {
    /* Declared members, and the @property names Cesium documents its option
       bags with rather than declaring them. */
    const d = l.match(/^\s*(?:static |readonly |declare )*([A-Za-z_$][\w$]*)\??[:(]/);
    if (d) found.add(d[1]);
    const p = l.match(/@property \[?([A-Za-z_$][\w$]*)/);
    if (p) found.add(p[1]);
    /* Enum values: "WHEEL = 3,". */
    const e = l.match(/^\s*([A-Z][A-Z0-9_]*)\s*=\s*[^=]/);
    if (e) found.add(e[1]);
  }
  return [...found].sort();
}

/* Only what globe.js touches: the manifest exists to check that file, not to
   mirror a library. */
const TRACKED = ['Viewer', 'Cartesian3', 'Color', 'HeightReference', 'Ellipsoid',
  'Credit', 'ArcGisMapServerImageryProvider', 'CesiumTerrainProvider',
  'EntityCollection', 'ImageryLayerCollection', 'CreditDisplay', 'Entity',
  'PointGraphics', 'SkyAtmosphere', 'Scene',
  /* The camera controls: how wheel, pinch and the zoom buttons move it. */
  'ScreenSpaceCameraController', 'Camera', 'CameraEventType', 'KeyboardEventModifier'];

const manifest = {
  note: 'Generated by tools/cesium-manifest.js from the published Cesium type definitions. Do not hand-edit.',
  version: version,
  generatedAt: new Date().toISOString(),
  exports: [...exported].sort(),
  members: {}
};
for (const t of TRACKED) manifest.members[t] = membersOf(t);

fs.writeFileSync(out, JSON.stringify(manifest, null, 2) + '\n');
console.log('manifest: ' + manifest.exports.length + ' exports, ' +
  TRACKED.length + ' tracked types -> ' + out);
